"""User-facing calculation rules, kept out of the independent calculation engine."""
import streamlit as st


def display_help():
    with st.expander('도움말 · 계산 기준'):
        st.markdown('''**실제시각과 날짜 추정**

- 계획은 STA/STD, 실제는 RAMP IN/OUT을 사용합니다. RAMP가 없으면 예정시각으로 대체합니다.
- 실제 날짜가 명시되면 원본 날짜를 사용합니다. 시각만 있으면 예정시각보다 최대 3시간 조기를 허용하는 가장 이른 날짜로 추정합니다.
- 예: 예정 26일 10:00, RAMP 08:00 → 26일 08:00. RAMP 06:00 → 27일 06:00으로 추정합니다.
- 예정 26일 10:00, RAMP 11:00은 1시간 지연으로 봅니다. 실제로 25시간 지연됐더라도 시각만으로 구별할 수 없습니다.
- DLA의 구체적인 부여 기준이 확인되지 않아 날짜 결정에는 사용하지 않습니다. 날짜 추정은 실제 날짜 확인을 뜻하지 않습니다.

**퀵턴 연결과 점유**

- 실제 기준에서 출발·도착을 모두 사용할 때 적용합니다. 기본은 미적용, 제한시간은 1~360분입니다.
- REG·SPOT이 모두 같고, 유효한 RAMP IN 이후 제한시간 이내에 RAMP OUT이 있는 명확한 도착→출발 한 쌍만 연결합니다. 제한시간과 정확히 같은 간격도 포함합니다.
- 예정시각 대체편, 정보 누락·불일치·후보 충돌은 연결하지 않습니다. 날짜 추정 RAMP는 위 날짜 규칙에 따라 사용합니다.
- 같은 기체의 중간 운항은 연결을 끊는 근거로 참고하며, 선택 밖 항공사의 편수를 분석에 더하지 않습니다.
- 두 조업 시작 중 이른 시각부터 종료 중 늦은 시각까지 대기시간도 같은 1개 조가 계속 점유합니다. 마지막에 출발편 이동시간만 더합니다.
- 제한시간은 RAMP IN~OUT 간격으로, 설정한 조업 시작~종료 길이와 다릅니다. 대기를 포함하므로 일부 시간대의 수요나 총 조·시간이 늘 수도 있습니다.

**필요 조 수·편수·운영일**

- 연결된 도착 1편·출발 1편은 운항편 2편, 조업 작업 1건입니다. 출발·도착 편수는 연결 전 운항편 기준으로 유지합니다.
- 필요 조 수는 같은 순간의 최대 점유입니다. 퀵턴 적용 시 출발 단독 + 도착 단독 + 연결 점유의 합이며, 각 분류의 독립 최대를 더하지 않습니다.
- 점유는 조업 시작 이상, 재투입 가능 시각 미만입니다. 끝나는 순간 다른 작업에 바로 투입할 수 있습니다.
- 피크 목록은 이동을 포함한 점유, 시간대 목록은 이동을 제외한 조업 구간 기준입니다. 연결 작업의 대기는 조업 구간에 포함됩니다.
- 조업 개시 시간은 운영일 경계입니다. 예: 02:00이면 해당 날짜 02:00부터 다음 날 02:00 직전까지 집계합니다. 오전·오후 최대는 한국시간 정오·자정 기준입니다.
- 제외한 방향의 —는 미분석을 뜻하며 0편과 다릅니다. 같은 편이나 작업이 여러 시간대 목록에 나타날 수 있습니다.

**조회와 결과 확인**

- 설정을 바꾸면 이전 결과임을 안내하며, 분석 실행 후 성공한 결과만 교체합니다. 실패·중단 시 이전 결과를 유지합니다.
- URL은 설정만 복원하며 자동 조회하지 않습니다. 다운로드는 현재 적용된 결과의 설정을 사용합니다.
- 분석 실행은 유효한 캐시를 활용하고, 새로 조회는 캐시를 우회합니다. 외부 자료가 갱신되면 같은 조건의 결과도 달라질 수 있습니다.
''')
